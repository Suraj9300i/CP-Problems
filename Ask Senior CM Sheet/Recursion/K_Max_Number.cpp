int rec(vector<int> &arr, int n){
    if(n == 0) return arr[0];
    return max(arr[n], rec(arr, n-1));
}

void solve() {
    int n;
    cin>>n;
    vector<int> arr(n);
    for(int i=0; i<n; i++){
        cin>>arr[i];
    }

    cout<<rec(arr, n-1);

}

